// Command genkeysyms writes the xkb package's keysym tables: the names
// come from libxkbcommon's xkbcommon-keysyms.h, and the canonical names,
// the Unicode conversions and the case mappings from asking libxkbcommon
// itself, so the tables are the library's own answers.
//
//	genkeysyms -header xkbcommon-keysyms.h -out keysym_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/ebitengine/purego"

	"github.com/stubbedev/lys-lib/clib"
)

var defineRE = regexp.MustCompile(`(?m)^#define XKB_KEY_(\w+)\s+(0x[0-9a-fA-F]+)`)

const (
	unicodeOffset = 0x01000000
	unicodeMax    = 0x0110ffff
	scanLow       = 0x20000
	caseInsens    = 1
)

type library struct {
	getName    func(sym uint32, buf *byte, size uintptr) int32
	fromName   func(name *byte, flags int32) uint32
	toUTF32    func(sym uint32) uint32
	fromUTF32  func(ucs uint32) uint32
	toUpper    func(sym uint32) uint32
	toLower    func(sym uint32) uint32
	symbolBase uintptr
}

func load() (*library, error) {
	h, err := clib.Open(clib.SystemCandidates("libxkbcommon.so.0"))
	if err != nil {
		return nil, fmt.Errorf("load libxkbcommon: %w", err)
	}
	l := &library{symbolBase: h}
	for _, f := range []struct {
		fn   any
		name string
	}{
		{&l.getName, "xkb_keysym_get_name"},
		{&l.fromName, "xkb_keysym_from_name"},
		{&l.toUTF32, "xkb_keysym_to_utf32"},
		{&l.fromUTF32, "xkb_utf32_to_keysym"},
		{&l.toUpper, "xkb_keysym_to_upper"},
		{&l.toLower, "xkb_keysym_to_lower"},
	} {
		if _, err := purego.Dlsym(h, f.name); err != nil {
			return nil, fmt.Errorf("libxkbcommon lacks %s: %w", f.name, err)
		}
		purego.RegisterLibFunc(f.fn, h, f.name)
	}
	return l, nil
}

func (l *library) name(sym uint32) string {
	buf := make([]byte, 128)
	n := l.getName(sym, &buf[0], uintptr(len(buf)))
	if n < 0 {
		return ""
	}
	return string(buf[:n])
}

func (l *library) foldLookup(name string) uint32 {
	b := append([]byte(name), 0)
	return l.fromName(&b[0], caseInsens)
}

type define struct {
	name string
	sym  uint32
}

func parseHeader(src []byte) ([]define, error) {
	matches := defineRE.FindAllSubmatch(src, -1)
	defines := make([]define, 0, len(matches))
	for _, m := range matches {
		v, err := strconv.ParseUint(string(m[2]), 0, 32)
		if err != nil {
			return nil, fmt.Errorf("parse the value of %s: %w", m[1], err)
		}
		defines = append(defines, define{string(m[1]), uint32(v)})
	}
	return defines, nil
}

func constName(name string) string {
	var b strings.Builder
	for part := range strings.SplitSeq(name, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return "Key" + b.String()
}

func constNames(defines []define) (map[string]string, error) {
	groups := map[string][]string{}
	for _, d := range defines {
		c := constName(d.name)
		groups[c] = append(groups[c], d.name)
	}
	out := make(map[string]string, len(defines))
	used := map[string]string{}
	assign := func(c, name string) error {
		if other, taken := used[c]; taken {
			return fmt.Errorf("constant %s stands for both %s and %s", c, other, name)
		}
		used[c] = name
		out[name] = c
		return nil
	}
	keys := make([]string, 0, len(groups))
	for c := range groups {
		keys = append(keys, c)
	}
	slices.Sort(keys)
	for _, c := range keys {
		names := groups[c]
		slices.Sort(names)
		if err := assign(c, names[0]); err != nil {
			return nil, err
		}
		for _, name := range names[1:] {
			if err := assign("Key"+name, name); err != nil {
				return nil, err
			}
		}
	}
	return out, nil
}

func generate(defines []define, l *library) ([]byte, error) {
	consts, err := constNames(defines)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by genkeysyms. DO NOT EDIT.\n\npackage xkb\n\n")
	b.WriteString("// The keysyms xkbcommon-keysyms.h names.\nconst (\n")
	for _, d := range defines {
		fmt.Fprintf(&b, "\t%s Keysym = %#x\n", consts[d.name], d.sym)
	}
	b.WriteString(")\n\n")

	byName := slices.Clone(defines)
	slices.SortFunc(byName, func(a, c define) int { return strings.Compare(a.name, c.name) })
	b.WriteString("var keysymNames = []keysymName{\n")
	for _, d := range byName {
		fmt.Fprintf(&b, "\t{%q, %#x},\n", d.name, d.sym)
	}
	b.WriteString("}\n\n")

	syms := map[uint32]bool{}
	for _, d := range defines {
		syms[d.sym] = true
	}
	sorted := make([]uint32, 0, len(syms))
	for s := range syms {
		sorted = append(sorted, s)
	}
	slices.Sort(sorted)
	b.WriteString("var keysymCanonical = []keysymName{\n")
	for _, s := range sorted {
		if s != 0 {
			fmt.Fprintf(&b, "\t{%q, %#x},\n", l.name(s), s)
		}
	}
	b.WriteString("}\n\n")

	folds := map[string]uint32{}
	for _, d := range defines {
		lower := asciiLower(d.name)
		if _, done := folds[lower]; !done {
			folds[lower] = l.foldLookup(lower)
		}
	}
	foldNames := make([]string, 0, len(folds))
	for n := range folds {
		foldNames = append(foldNames, n)
	}
	slices.Sort(foldNames)
	b.WriteString("var keysymFolded = []keysymName{\n")
	for _, n := range foldNames {
		fmt.Fprintf(&b, "\t{%q, %#x},\n", n, folds[n])
	}
	b.WriteString("}\n\n")

	scan := make([]uint32, 0, scanLow+len(sorted))
	for s := range uint32(scanLow) {
		scan = append(scan, s)
	}
	for _, s := range sorted {
		if s >= scanLow {
			scan = append(scan, s)
		}
	}
	b.WriteString("var keysymToUCS = []keysymRune{\n")
	for _, s := range scan {
		if s >= unicodeOffset && s <= unicodeMax {
			continue
		}
		if cp := l.toUTF32(s); cp != 0 {
			fmt.Fprintf(&b, "\t{%#x, %#x},\n", s, cp)
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("var ucsToKeysym = []runeKeysym{\n")
	for cp := uint32(1); cp <= 0x10ffff; cp++ {
		if cp >= 0xd800 && cp <= 0xdfff {
			continue
		}
		if sym := l.fromUTF32(cp); sym != unicodeOffset+cp {
			fmt.Fprintf(&b, "\t{%#x, %#x},\n", cp, sym)
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("var keysymCase = []caseMapping{\n")
	emit := func(s uint32) {
		upper, lower := l.toUpper(s), l.toLower(s)
		if upper != s || lower != s {
			fmt.Fprintf(&b, "\t{%#x, %#x, %#x},\n", s, upper, lower)
		}
	}
	for _, s := range scan {
		if s < unicodeOffset {
			emit(s)
		}
	}
	for s := uint32(unicodeOffset); s <= unicodeMax; s++ {
		emit(s)
	}
	for _, s := range scan {
		if s > unicodeMax {
			emit(s)
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func asciiLower(s string) string {
	b := []byte(s)
	for i, c := range b {
		if c >= 'A' && c <= 'Z' {
			b[i] = c + 'a' - 'A'
		}
	}
	return string(b)
}

func main() {
	header := flag.String("header", os.Getenv("LYS_XKB_KEYSYMS_H"), "path of xkbcommon-keysyms.h")
	out := flag.String("out", "keysym_gen.go", "file to write")
	flag.Parse()
	if *header == "" {
		log.Fatal("genkeysyms: -header or LYS_XKB_KEYSYMS_H is required")
	}
	src, err := os.ReadFile(*header) //nolint:gosec // the path the generator was given
	if err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
	defines, err := parseHeader(src)
	if err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
	l, err := load()
	if err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
	text, err := generate(defines, l)
	if err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
	tmp := *out + ".tmp"
	if err := os.WriteFile(tmp, text, 0o644); err != nil { //nolint:gosec // a source file
		log.Fatalf("genkeysyms: %v", err)
	}
	if err := os.Rename(tmp, *out); err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
}
