// Command genkeysyms writes the xkb package's keysym tables: the names
// come from libxkbcommon's xkbcommon-keysyms.h, and the canonical names,
// the Unicode conversions and the case mappings from asking libxkbcommon
// itself, so the tables are the library's own answers.
//
//	genkeysyms -header xkbcommon-keysyms.h -out keysym_gen.go
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"runtime"
	"slices"
	"strconv"
	"strings"
	"unsafe"

	"github.com/ebitengine/purego"

	"github.com/stubbedev/lys-lib/clib"
)

var defineRE = regexp.MustCompile(`(?m)^#define XKB_KEY_(\w+)\s+(0x[0-9a-fA-F]+)`)

const (
	unicodeOffset = 0x01000000
	unicodeMax    = 0x0110ffff
	scanLow       = 0x20000
	caseInsens    = 1
)

type library struct {
	getName    func(sym uint32, buf *byte, size uintptr) int32
	fromName   func(name *byte, flags int32) uint32
	toUTF32    func(sym uint32) uint32
	fromUTF32  func(ucs uint32) uint32
	toUpper    func(sym uint32) uint32
	toLower    func(sym uint32) uint32
	context    func(flags int32) uintptr
	fromString func(ctx uintptr, s *byte, format, flags int32) uintptr
	modsLevel  func(km uintptr, kc, layout, level uint32, out *uint32, size uintptr) uintptr
	unref      func(km uintptr)
	symbolBase uintptr
}

func load() (*library, error) {
	h, err := clib.Open(clib.SystemCandidates("libxkbcommon.so.0"))
	if err != nil {
		return nil, fmt.Errorf("load libxkbcommon: %w", err)
	}
	l := &library{symbolBase: h}
	for _, f := range []struct {
		fn   any
		name string
	}{
		{&l.getName, "xkb_keysym_get_name"},
		{&l.fromName, "xkb_keysym_from_name"},
		{&l.toUTF32, "xkb_keysym_to_utf32"},
		{&l.fromUTF32, "xkb_utf32_to_keysym"},
		{&l.toUpper, "xkb_keysym_to_upper"},
		{&l.toLower, "xkb_keysym_to_lower"},
		{&l.context, "xkb_context_new"},
		{&l.fromString, "xkb_keymap_new_from_string"},
		{&l.modsLevel, "xkb_keymap_key_get_mods_for_level"},
		{&l.unref, "xkb_keymap_unref"},
	} {
		if _, err := purego.Dlsym(h, f.name); err != nil {
			return nil, fmt.Errorf("libxkbcommon lacks %s: %w", f.name, err)
		}
		purego.RegisterLibFunc(f.fn, h, f.name)
	}
	return l, nil
}

func (l *library) name(sym uint32) string {
	buf := make([]byte, 128)
	n := l.getName(sym, &buf[0], uintptr(len(buf)))
	if n < 0 {
		return ""
	}
	return string(buf[:n])
}

func (l *library) foldLookup(name string) uint32 {
	b := append([]byte(name), 0)
	return l.fromName(&b[0], caseInsens)
}

type define struct {
	name string
	sym  uint32
}

func parseHeader(src []byte) ([]define, error) {
	matches := defineRE.FindAllSubmatch(src, -1)
	defines := make([]define, 0, len(matches))
	for _, m := range matches {
		v, err := strconv.ParseUint(string(m[2]), 0, 32)
		if err != nil {
			return nil, fmt.Errorf("parse the value of %s: %w", m[1], err)
		}
		defines = append(defines, define{string(m[1]), uint32(v)})
	}
	return defines, nil
}

func constName(name string) string {
	var b strings.Builder
	for part := range strings.SplitSeq(name, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return "Key" + b.String()
}

func constNames(defines []define) (map[string]string, error) {
	groups := map[string][]string{}
	for _, d := range defines {
		c := constName(d.name)
		groups[c] = append(groups[c], d.name)
	}
	out := make(map[string]string, len(defines))
	used := map[string]string{}
	assign := func(c, name string) error {
		if other, taken := used[c]; taken {
			return fmt.Errorf("constant %s stands for both %s and %s", c, other, name)
		}
		used[c] = name
		out[name] = c
		return nil
	}
	keys := make([]string, 0, len(groups))
	for c := range groups {
		keys = append(keys, c)
	}
	slices.Sort(keys)
	for _, c := range keys {
		names := groups[c]
		slices.Sort(names)
		if err := assign(c, names[0]); err != nil {
			return nil, err
		}
		for _, name := range names[1:] {
			if err := assign("Key"+name, name); err != nil {
				return nil, err
			}
		}
	}
	return out, nil
}

func generate(defines []define, l *library) ([]byte, error) {
	consts, err := constNames(defines)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by genkeysyms. DO NOT EDIT.\n\npackage xkb\n\n")
	b.WriteString("// The keysyms xkbcommon-keysyms.h names.\nconst (\n")
	for _, d := range defines {
		fmt.Fprintf(&b, "\t%s Keysym = %#x\n", consts[d.name], d.sym)
	}
	b.WriteString(")\n\n")

	byName := slices.Clone(defines)
	slices.SortFunc(byName, func(a, c define) int { return strings.Compare(a.name, c.name) })
	b.WriteString("var keysymNames = []keysymName{\n")
	for _, d := range byName {
		fmt.Fprintf(&b, "\t{%q, %#x},\n", d.name, d.sym)
	}
	b.WriteString("}\n\n")

	syms := map[uint32]bool{}
	for _, d := range defines {
		syms[d.sym] = true
	}
	sorted := make([]uint32, 0, len(syms))
	for s := range syms {
		sorted = append(sorted, s)
	}
	slices.Sort(sorted)
	b.WriteString("var keysymCanonical = []keysymName{\n")
	for _, s := range sorted {
		if s != 0 {
			fmt.Fprintf(&b, "\t{%q, %#x},\n", l.name(s), s)
		}
	}
	b.WriteString("}\n\n")

	folds := map[string]uint32{}
	for _, d := range defines {
		lower := asciiLower(d.name)
		if _, done := folds[lower]; !done {
			folds[lower] = l.foldLookup(lower)
		}
	}
	foldNames := make([]string, 0, len(folds))
	for n := range folds {
		foldNames = append(foldNames, n)
	}
	slices.Sort(foldNames)
	b.WriteString("var keysymFolded = []keysymName{\n")
	for _, n := range foldNames {
		fmt.Fprintf(&b, "\t{%q, %#x},\n", n, folds[n])
	}
	b.WriteString("}\n\n")

	scan := make([]uint32, 0, scanLow+len(sorted))
	for s := range uint32(scanLow) {
		scan = append(scan, s)
	}
	for _, s := range sorted {
		if s >= scanLow {
			scan = append(scan, s)
		}
	}
	b.WriteString("var keysymToUCS = []keysymRune{\n")
	for _, s := range scan {
		if s >= unicodeOffset && s <= unicodeMax {
			continue
		}
		if cp := l.toUTF32(s); cp != 0 {
			fmt.Fprintf(&b, "\t{%#x, %#x},\n", s, cp)
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("var ucsToKeysym = []runeKeysym{\n")
	for cp := uint32(1); cp <= 0x10ffff; cp++ {
		if cp >= 0xd800 && cp <= 0xdfff {
			continue
		}
		if sym := l.fromUTF32(cp); sym != unicodeOffset+cp {
			fmt.Fprintf(&b, "\t{%#x, %#x},\n", cp, sym)
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("var keysymCase = []caseMapping{\n")
	all := append(slices.Clone(scan), unicodeSyms()...)
	lowers, uppers, err := l.caseProperties(all)
	if err != nil {
		return nil, err
	}
	emit := func(s uint32) {
		upper, lower := l.toUpper(s), l.toLower(s)
		var flags uint8
		if lowers[s] {
			flags |= 1
		}
		if uppers[s] {
			flags |= 2
		}
		if upper != s || lower != s || flags != 0 {
			fmt.Fprintf(&b, "\t{%#x, %#x, %#x, %d},\n", s, upper, lower, flags)
		}
	}
	for _, s := range scan {
		if s < unicodeOffset {
			emit(s)
		}
	}
	for s := uint32(unicodeOffset); s <= unicodeMax; s++ {
		emit(s)
	}
	for _, s := range scan {
		if s > unicodeMax {
			emit(s)
		}
	}
	b.WriteString("}\n\n")
	deprecated, err := l.deprecations(defines)
	if err != nil {
		return nil, err
	}
	b.WriteString(deprecated)
	return format.Source(b.Bytes())
}

func asciiLower(s string) string {
	b := []byte(s)
	for i, c := range b {
		if c >= 'A' && c <= 'Z' {
			b[i] = c + 'a' - 'A'
		}
	}
	return string(b)
}

func main() {
	header := flag.String("header", os.Getenv("LYS_XKB_KEYSYMS_H"), "path of xkbcommon-keysyms.h")
	out := flag.String("out", "keysym_gen.go", "file to write")
	flag.Parse()
	if *header == "" {
		log.Fatal("genkeysyms: -header or LYS_XKB_KEYSYMS_H is required")
	}
	src, err := os.ReadFile(*header) //nolint:gosec // the path the generator was given
	if err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
	defines, err := parseHeader(src)
	if err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
	l, err := load()
	if err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
	text, err := generate(defines, l)
	if err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
	tmp := *out + ".tmp"
	if err := os.WriteFile(tmp, text, 0o644); err != nil { //nolint:gosec // a source file
		log.Fatalf("genkeysyms: %v", err)
	}
	if err := os.Rename(tmp, *out); err != nil {
		log.Fatalf("genkeysyms: %v", err)
	}
}

func unicodeSyms() []uint32 {
	out := make([]uint32, 0, unicodeMax-unicodeOffset+1)
	for s := uint32(unicodeOffset); s <= unicodeMax; s++ {
		out = append(out, s)
	}
	return out
}

const caseBatch = 8192

const caseProbeHeader = `xkb_keymap {
xkb_keycodes { minimum = 8; maximum = %d;
%s};
xkb_types {
	virtual_modifiers NumLock;
	type "ONE_LEVEL" { modifiers= none; };
	type "TWO_LEVEL" { modifiers= Shift; map[Shift]= 2; };
	type "ALPHABETIC" { modifiers= Shift+Lock; map[Shift]= 2; map[Lock]= 2; };
};
xkb_compatibility { };
xkb_symbols {
%s};
};
`

// caseProperties asks libxkbcommon which keysyms count as lower and upper
// case when it picks a key's automatic type: the Unicode properties, which
// include characters with no case mapping and so cannot be derived from
// xkb_keysym_to_upper and xkb_keysym_to_lower. A key of [sym, A] is ALPHABETIC
// when sym is lower case and one of [a, sym] when sym is upper case; ALPHABETIC
// is the type that maps Lock to level 2.
func (l *library) caseProperties(syms []uint32) (lowers, uppers map[uint32]bool, err error) {
	ctx := l.context(0)
	if ctx == 0 {
		return nil, nil, errors.New("xkb_context_new failed")
	}
	lowers, uppers = map[uint32]bool{}, map[uint32]bool{}
	for start := 0; start < len(syms); start += caseBatch {
		batch := syms[start:min(start+caseBatch, len(syms))]
		var codes, keys strings.Builder
		for i, s := range batch {
			fmt.Fprintf(&codes, "<L%d> = %d;\n<U%d> = %d;\n", i, 2*i+8, i, 2*i+9)
			fmt.Fprintf(&keys, "key <L%d> { [ %#x, A ] };\nkey <U%d> { [ a, %#x ] };\n", i, s, i, s)
		}
		text := append(fmt.Appendf(nil, caseProbeHeader, 2*len(batch)+9, codes.String(), keys.String()), 0)
		km := l.fromString(ctx, &text[0], 1, 0)
		runtime.KeepAlive(text)
		if km == 0 {
			return nil, nil, fmt.Errorf("the case probe keymap for keysyms from %#x does not compile", batch[0])
		}
		for i, s := range batch {
			var masks [4]uint32
			if n := l.modsLevel(km, uint32(2*i+8), 0, 1, &masks[0], 4); n == 2 {
				lowers[s] = true
			}
			if n := l.modsLevel(km, uint32(2*i+9), 0, 1, &masks[0], 4); n == 2 {
				uppers[s] = true
			}
		}
		l.unref(km)
	}
	return lowers, uppers, nil
}

const deprecationProbe = `xkb_keymap {
xkb_keycodes { minimum = 8; maximum = 9; <K> = 8; };
xkb_types { type "ONE_LEVEL" { modifiers= none; }; };
xkb_compatibility { };
xkb_symbols { key <K> { [ %s ] }; };
};
`

type deprecationProber struct {
	lib       *library
	ctx       uintptr
	vsnprintf func(buf *byte, size uintptr, format, args unsafe.Pointer) int32
	message   string
}

var activeProber *deprecationProber

// deprecation asks libxkbcommon whether it warns about a keysym spelled a
// given way, and which name it recommends instead, from its own log: the table
// of deprecated keysyms is private to the library.
func (p *deprecationProber) deprecation(spelling string) (deprecated bool, reference string) {
	p.message = ""
	text := append(fmt.Appendf(nil, deprecationProbe, spelling), 0)
	km := p.lib.fromString(p.ctx, &text[0], 1, 0)
	runtime.KeepAlive(text)
	if km != 0 {
		p.lib.unref(km)
	}
	switch {
	case strings.Contains(p.message, "[XKB-302]"):
		_, rest, _ := strings.Cut(p.message, "please use \"")
		name, _, _ := strings.Cut(rest, "\"")
		return true, name
	case strings.Contains(p.message, "[XKB-301]"):
		return true, ""
	}
	return false, ""
}

func newDeprecationProber(l *library) (*deprecationProber, error) {
	c, err := clib.Open([]string{"libc.so.6"})
	if err != nil {
		return nil, fmt.Errorf("load libc: %w", err)
	}
	p := &deprecationProber{lib: l, ctx: l.context(0)}
	purego.RegisterLibFunc(&p.vsnprintf, c, "vsnprintf")
	var setLevel func(ctx uintptr, level int32)
	var setVerbosity func(ctx uintptr, verbosity int32)
	var setLogFn func(ctx, fn uintptr)
	purego.RegisterLibFunc(&setLevel, l.symbolBase, "xkb_context_set_log_level")
	purego.RegisterLibFunc(&setVerbosity, l.symbolBase, "xkb_context_set_log_verbosity")
	purego.RegisterLibFunc(&setLogFn, l.symbolBase, "xkb_context_set_log_fn")
	setLevel(p.ctx, 30)
	setVerbosity(p.ctx, 2)
	activeProber = p
	setLogFn(p.ctx, purego.NewCallback(func(_ uintptr, _ int32, format, args unsafe.Pointer) uintptr {
		var buf [512]byte
		n := activeProber.vsnprintf(&buf[0], uintptr(len(buf)), format, args)
		if n > 0 {
			activeProber.message += string(buf[:min(int(n), len(buf)-1)])
		}
		return 0
	}))
	return p, nil
}

func (l *library) deprecations(defines []define) (string, error) {
	p, err := newDeprecationProber(l)
	if err != nil {
		return "", err
	}
	var b bytes.Buffer
	b.WriteString("var keysymDeprecatedNames = []deprecatedName{\n")
	names := make([]string, 0, len(defines))
	seen := map[uint32]bool{}
	syms := make([]uint32, 0, len(defines))
	for _, d := range defines {
		names = append(names, d.name)
		if !seen[d.sym] {
			seen[d.sym] = true
			syms = append(syms, d.sym)
		}
	}
	slices.Sort(names)
	names = slices.Compact(names)
	for _, name := range names {
		if deprecated, ref := p.deprecation(name); deprecated {
			fmt.Fprintf(&b, "\t{%q, %q},\n", name, ref)
		}
	}
	b.WriteString("}\n\nvar keysymDeprecatedValues = []Keysym{\n")
	slices.Sort(syms)
	for _, s := range syms {
		if deprecated, _ := p.deprecation(fmt.Sprintf("%#x", s)); deprecated {
			fmt.Fprintf(&b, "\t%#x,\n", s)
		}
	}
	b.WriteString("}\n")
	return b.String(), nil
}
